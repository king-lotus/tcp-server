#!/usr/bin/env python3
"""Compile and run verify/close_state_machine.cpp on a host without epoll.

The header is Linux-only: it includes <sys/epoll.h> and refuses to build
anywhere else. But the close state machine is a pure function of
(phase, event, facts) by construction -- it touches no socket, no epoll set and
no counter -- so that one section *can* be built and run anywhere with a C++17
compiler. This script lifts the section out of the header verbatim, pastes it in
front of the same test file the Linux suite compiles, and runs it.

That is not a substitute for verify/run.sh. It covers decide(), which is the
part R3 introduced; it covers none of the runtime behaviour around it.

    python verify/evidence/extract_close_sm.py
    python verify/evidence/extract_close_sm.py --cxx /c/msys64/ucrt64/bin/g++.exe
    python verify/evidence/extract_close_sm.py --keep      # leave the .cpp behind

Exit code is the test's.
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile

BEGIN = '// ==================== Close state ===================='
DECIDE = 'inline CloseAction decide('


def find_section(text):
    start = text.index(BEGIN)
    d = text.index(DECIDE, start)
    # decide()'s body ends at the first line that is exactly "}" at column 0.
    lines = text[d:].split('\n')
    end = None
    for i, ln in enumerate(lines):
        if ln.rstrip() == '}':
            end = i
            break
    if end is None:
        raise SystemExit('could not find the end of decide()')
    return text[start:d + len('\n'.join(lines[:end + 1]))]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--cxx', default=shutil.which('g++') or 'g++')
    ap.add_argument('--keep', action='store_true')
    ap.add_argument('--repo', default=os.path.dirname(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    args = ap.parse_args()

    header = os.path.join(args.repo, 'include', 'tcp-server-mt.h')
    test = os.path.join(args.repo, 'verify', 'close_state_machine.cpp')
    for p in (header, test):
        if not os.path.exists(p):
            raise SystemExit('missing: %s' % p)

    section = find_section(open(header, encoding='utf-8').read())

    shim = (
        '// generated by verify/evidence/extract_close_sm.py -- do not edit\n'
        '#include <atomic>\n'
        '#include <cstdint>\n'
        '#include <cstdio>\n'
        '#include <cstring>\n'
        'namespace industrial {\n'
        + section +
        '\n}  // namespace industrial\n'
        '\n#define CLOSE_SM_STANDALONE 1\n'
        '#include "%s"\n' % test.replace('\\', '/')
    )

    tmpdir = tempfile.mkdtemp(prefix='close_sm_')
    cpp = os.path.join(tmpdir, 'close_sm.cpp')
    exe = os.path.join(tmpdir, 'close_sm.exe' if os.name == 'nt' else 'close_sm')
    open(cpp, 'w', encoding='utf-8').write(shim)

    try:
        print('== compiling with %s ==' % args.cxx)
        # g++ finds cc1plus, as and ld through PATH; a compiler named by
        # absolute path does not imply its own directory is on it.
        env = dict(os.environ)
        env['PATH'] = os.path.dirname(os.path.abspath(args.cxx)) + os.pathsep \
            + env.get('PATH', '')
        r = subprocess.run([args.cxx, '-std=c++17', '-Wall', '-Wextra',
                            '-O1', cpp, '-o', exe],
                           capture_output=True, text=True, env=env)
        if r.stdout.strip():
            print(r.stdout)
        if r.stderr.strip():
            print(r.stderr)
        if r.returncode != 0:
            print('compile failed')
            return 1
        print('== running ==')
        run = subprocess.run([exe], capture_output=True, text=True)
        print(run.stdout)
        if run.stderr.strip():
            print(run.stderr)
        return run.returncode
    finally:
        if args.keep:
            print('kept: %s' % cpp)
        else:
            shutil.rmtree(tmpdir, ignore_errors=True)


if __name__ == '__main__':
    sys.exit(main())
